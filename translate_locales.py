def generate_all_locales():
    """Generates all 23 language locale JSON files with English fallback and metadata."""
    generated_count = 0
    for code, meta in LANGUAGES_METADATA.items():
        locale_data = {
            "_metadata": {
                "code": code,
                "name_en": meta["name_en"],
                "name_native": meta["name_native"],
                "direction": meta["dir"],
                "font_family": meta["font"]
            }
        }

        # Apply specific translations or English fallback
        specific = TRANSLATIONS_OVERRIDE.get(code, {})
        for k, v in MASTER_ENGLISH.items():
            locale_data[k] = specific.get(k, v)

        file_path = LOCALES_DIR / f"{code}.json"
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(locale_data, f, ensure_ascii=False, indent=2)
        generated_count += 1

    print(f"[OK] Successfully generated {generated_count} locale files in {LOCALES_DIR}")
    return generated_count

if __name__ == "__main__":
    generate_all_locales()
